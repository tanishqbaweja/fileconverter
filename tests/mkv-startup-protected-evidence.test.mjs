const file = "evidence/2026-11-15T00-06-48-699Z-mkv-startup-core-protected.json";
const read = name => readFile(new URL(`../${name}`, import.meta.url));
const sha = b => createHash("sha256").update(b).digest("hex");
test("Changed startup core genuinely remuxes the full protected original and binds all output bytes to complete independent validators", async () => {
  const bytes = await read(file); assert.equal(sha(bytes), "d256385dadb3a0290ced4dc61c04288ab0b6d964bdcc08fa2f85e9fa0944f64f");
  const r = JSON.parse(bytes), [a] = r.arms, [c] = a.cases, v = c.validation;
  assert.equal(r.status, "passed-startup-core-protected-not-public-acceptance");
  assert.equal(r.startupProtectedCandidate, true); assert.equal(r.originalMediaSelected, true);
  assert.equal(c.selection.completeOriginalSelected, true); assert.equal(c.selection.sourceCopyCreated, false);
  assert.equal(c.selection.remotePlaywrightUpload, false); assert.equal(c.selection.alternateConversionPath, false);
  assert.deepEqual(r.originalBefore, r.originalAfter); assert.equal(r.originalAfter.bytes, 2958573265);
  assert.equal(r.originalAfter.sha256, "31f36695b5b44c62125a9e4264e84dc085accd21c02cc3487aae597f54b9db34");
  assert.equal(c.metrics.inputBytes, 2958573265); assert.equal(c.metrics.outputBytes, 2962151594);
  assert.equal(c.metrics.elapsedMs, 28982.40999996662);
  const reference = readStartupProtectedReference(await read(protectedRepeatReference.file), await read(protectedCompleteVideoReference.file), r.candidateBuild);
  assert.equal(v.outputSha256, reference.outputSha256); assert.equal(reference.outputBytes, c.metrics.outputBytes);
  assert.equal(v.independentValidation.nativeCoreEqualityClaimed, false);
  assert.equal(v.independentValidation.fullVideoDecodePerformedThisRun, false);
  assert.equal(v.independentValidation.independentlyDecodedVideoFrames, 296160);
  assert.equal(v.fullVideoDecode, false); assert.equal(v.fullVideoDecodeInheritedThroughWholeOutputIdentity, true);
  assert.ok(v.structure.streamPropertiesMatch && v.structure.languagePreserved && v.structure.subtitleDisclosed && v.structure.artworkDisclosed);
  assert.ok(v.structure.durationDeltaSeconds < 0.05 && v.candidateGate.passed);
  assert.equal(v.serializedTimeline.tracks[1].edits[0].mediaTimeTicks, "5058");
  assert.equal(c.binding.allOutputBytesCompared, false); assert.equal(c.binding.convertedCopyCreated, false);
  assert.ok(c.metrics.peakWasmMemoryBytes <= 64 * 1048576 && c.metrics.maxReadChunkBytes <= 262144);
  assert.ok(c.metrics.maxWriteChunkBytes <= 1048576 && c.metrics.peakQueuedBytes <= 1048576);
  assert.equal(c.metrics.peakPendingOperations, 1); assert.equal(c.metrics.pendingOperations, 0);
  assert.ok(r.diskPreflight.availableBytes >= r.diskPreflight.requiredBytes && r.hostPreflight.safeToStart);
  const packed = await read(a.archive.file); assert.equal(sha(packed), a.archive.sha256);
  const raw = gunzipSync(packed, { maxOutputLength: 4 * 1048576 }); assert.equal(sha(raw), a.archive.decodedSha256);
  const memory = summarizeProtectedWindow(JSON.parse(raw), a.memory, a.blank.privateBytes);
  assert.equal(memory.incrementalPrivateMiB, 222.12890625); assert.equal(memory.validSamples, 266); assert.equal(memory.unavailableSamples, 0);
  assert.equal(memory.cleanupAboveIdleMiB, 5.015625);
  assert.equal(a.browserCleanup.status, "owned-observed-pids-absent"); assert.equal(a.browserCleanup.observedPids.length, 42);
  assert.ok(c.outputRemoved && a.ownedRuntimeRemoved && a.serverCleanup.ownedRootAbsent && r.toolDownloadRemoved);
  for (const field of ["nativeConversionUsed", "headed", "browserServicesDisabled", "productionFilesReplaced", "speedGainProven", "publicAcceptance"]) assert.equal(r[field], false);
});
test("First changed-core major report renders truthful measured memory without implying repeats or another native decode", async () => {
  const r = JSON.parse(await read(file)), generated = renderProtectedRepeatReport(r);
  assert.equal(generated.csv, (await read(file.replace(/\.json$/, ".csv"))).toString());
  assert.equal(generated.html, (await read(file.replace(/\.json$/, ".html"))).toString());
  assert.match(generated.html, /first changed-core run/); assert.match(generated.html, /222\.129/);
  assert.match(generated.html, /no new full native decode or native-core equality is claimed/);
  assert.match(generated.csv, /2962151594,28982\.40999996662,222\.12890625,5\.015625,266,0/);
  const missing = structuredClone(r); delete missing.arms[0].memory;
  const unknown = renderProtectedRepeatReport(missing);
  assert.match(unknown.html, /S1 J1: unavailable/);
  assert.match(unknown.csv, /unavailable,unavailable,unavailable,unavailable/);
});

test("Current startup core completes three same-page original remuxes and a clean-session repeat with unchanged baselines and full byte identity", async () => {
  const name = "evidence/2026-11-15T00-10-16-881Z-mkv-startup-core-protected-repeats.json", bytes = await read(name);
  assert.equal(sha(bytes), "af3b6e677c7dabf146c541b59139c57df73207018383d859499e5cf0c803833e");
  const r = JSON.parse(bytes); assert.equal(r.status, "passed-startup-core-protected-repeats-not-public-acceptance");
  assert.equal(r.startupProtectedCandidate, true); assert.deepEqual(r.arms.map(a => a.cases.length), [3, 1]);
  assert.equal(r.originalMediaSelected, true); assert.deepEqual(r.originalBefore, r.originalAfter);
  assert.equal(r.candidateBuild.build.artifacts["within-direct.wasm"].sha256, "62cf939ce720022ebf73e2f7dcf82fcdcfc33e7e4221334d691b992a2f4ae8ef");
  const peaks = [], cleanups = [], times = [], counts = [], missing = [], pids = [];
  for (const a of r.arms) {
    const packed = await read(a.archive.file); assert.equal(sha(packed), a.archive.sha256);
    const raw = gunzipSync(packed, { maxOutputLength: 16 * 1048576 }); assert.equal(sha(raw), a.archive.decodedSha256);
    const samples = JSON.parse(raw);
    for (const c of a.cases) {
      assert.equal(c.state, "complete"); assert.equal(c.metrics.inputBytes, 2958573265); assert.equal(c.metrics.outputBytes, 2962151594);
      assert.equal(c.validation.outputSha256, "247c77c371340f8bfb090dc8f8cfde22d83ca1e83483672847013527c50d937b");
      assert.equal(c.validation.fullVideoDecode, false); assert.equal(c.validation.fullVideoDecodeInheritedThroughWholeOutputIdentity, true);
      assert.equal(c.validation.independentValidation.fullVideoDecodePerformedThisRun, false);
      assert.equal(c.validation.independentValidation.independentlyDecodedVideoFrames, 296160);
      assert.ok(c.validation.candidateGate.passed && c.outputRemoved);
      const memory = summarizeProtectedWindow(samples, c.conversionWindow, a.blank.privateBytes);
      assert.equal(memory.incrementalPrivateMiB, c.memory.incrementalPrivateMiB);
      assert.ok(c.cleanupAboveIdleMiB <= 96);
      peaks.push(memory.incrementalPrivateMiB); counts.push(memory.validSamples); missing.push(memory.unavailableSamples);
      cleanups.push(c.cleanupAboveIdleMiB); times.push(c.metrics.elapsedMs);
      assert.ok(c.metrics.peakQueuedBytes <= 1048576 && c.metrics.peakPendingOperations === 1);
      assert.ok(c.metrics.maxReadChunkBytes <= 262144 && c.metrics.maxWriteChunkBytes <= 1048576);
      assert.equal(c.metrics.peakWasmMemoryBytes, 52690944);
      assert.equal(c.selection.sourceCopyCreated, false); assert.equal(c.binding.convertedCopyCreated, false);
    }
    assert.equal(a.browserCleanup.status, "owned-observed-pids-absent"); pids.push(a.browserCleanup.observedPids.length);
    assert.ok(a.ownedRuntimeRemoved && a.serverCleanup.ownedRootAbsent);
    assert.deepEqual(a.forbiddenRequests, []);
  }
  assert.deepEqual(peaks, [225.28515625, 200.20703125, 163.234375, 211.17578125]);
  assert.deepEqual(cleanups, [23.51953125, 32.82421875, 19.01171875, -4.28125]);
  assert.deepEqual(times, [29093.77000004053, 53768.875, 33875.689999997616, 35352.99500000477]);
  assert.deepEqual(counts, [265, 492, 310, 322]); assert.deepEqual(missing, [1, 1, 0, 1]);
  assert.deepEqual(pids, [48, 50]); assert.equal(r.toolDownloadRemoved, true);
  const rendered = renderProtectedRepeatReport(r);
  assert.equal(rendered.csv, (await read(name.replace(/\.json$/, ".csv"))).toString());
  assert.equal(rendered.html, (await read(name.replace(/\.json$/, ".html"))).toString());
  assert.match(rendered.html, /225\.285/); assert.match(rendered.html, /no new full native decode/);
});
