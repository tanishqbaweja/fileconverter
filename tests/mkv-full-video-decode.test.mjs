test("Complete protected decode binds terminal proof to real output, all-process memory and cleanup", async () => {
  const read = file => readFile(new URL(`../${file}`, import.meta.url));
  const sha = bytes => createHash("sha256").update(bytes).digest("hex");
  const stem = "evidence/2026-11-14T09-24-11-075Z-mkv-exact-aac-protected-full-decode";
  const bytes = await read(stem + ".json");
  assert.equal(sha(bytes), "25b044e505807c7e3fa8a60db933d14e4819949228b22067f5540379f8985070");
  const report = JSON.parse(bytes), [arm] = report.arms, [row] = arm.cases;
  const reference = readProtectedRepeatReference(await read(protectedRepeatReference.file), report.candidateBuild);
  assert.equal(report.status, "passed-protected-complete-video-decode-not-public-acceptance");
  assert.equal(arm.status, "passed-protected-complete-video-decode");
  assert.equal(row.state, "complete");
  assert.equal(row.metrics.outputBytes, reference.outputBytes);
  assert.equal(row.validation.outputSha256, reference.outputSha256);
  assert.equal(row.validation.serializedTimeline.tracks[1].edits[0].mediaTimeTicks, "5058");
  assert.ok(row.validation.structure.subtitleDisclosed && row.validation.structure.artworkDisclosed);
  const decode = row.validation.completeVideo;
  assert.equal(decode.completedProgressReports, 24);
  assert.equal(decode.elapsedMs, 703241);
  assert.equal(decode.deadlineMs, FULL_VIDEO_VALIDATOR_DEADLINE_MS);
  assert.equal(decode.retainedDecodedFrames, 0);
  assert.equal(decode.decodedFileCreated, false);
  assert.equal(decode.nativeToolUsedForConversion, false);
  assert.equal(row.metrics.elapsedMs, 64755.814999997616);
  assert.ok(row.selection.completeOriginalSelected && row.outputRemoved);
  assert.equal(row.binding.convertedCopyCreated, false);
  assert.equal(row.metrics.peakScratchBytes ?? 0, 0);
  assert.ok(row.metrics.maxReadChunkBytes <= 262144 && row.metrics.maxWriteChunkBytes <= 1048576);
  assert.equal(row.metrics.peakPendingOperations, 1);
  assert.ok(row.metrics.peakQueuedBytes <= 1048576);
  assert.ok(row.metrics.peakWasmMemoryBytes <= 64 * 1048576);
  assert.deepEqual(arm.forbiddenRequests, []);
  assert.deepEqual(report.failures, []); assert.deepEqual(arm.failures, []);
  assert.equal(arm.browserCleanup.observedPids.length, 58);
  assert.equal(report.originalBefore.sha256, "31f36695b5b44c62125a9e4264e84dc085accd21c02cc3487aae597f54b9db34");
  assert.equal(report.originalBefore.bytes, 2958573265);
  assert.equal(report.publicAcceptance, false);
  assert.equal(report.nativeConversionUsed, false);
  assert.equal(report.headed, false);
  assert.equal(report.productionFilesReplaced, false);
  const archive = await read(arm.archive.file);
  assert.equal(sha(archive), arm.archive.sha256);
  const raw = gunzipSync(archive, { maxOutputLength: 32 * 1024 ** 2 });
  assert.equal(sha(raw), arm.archive.decodedSha256);
  const samples = JSON.parse(raw);
  assert.equal(samples.length, 7363);
  assert.equal(arm.memory.incrementalPrivateMiB, 187.05078125);
  assert.equal(arm.memory.cleanupAboveIdleMiB, 19.515625);
  assert.equal(arm.memory.validSamples, 592); assert.equal(arm.memory.unavailableSamples, 1);
  const rendered = renderFullVideoDecodeReport(report, samples);
  assert.equal((await read(stem + ".csv")).toString(), rendered.csv);
  assert.equal((await read(stem + ".html")).toString(), rendered.html);
  assert.match(rendered.csv, /unavailable,unavailable,false/);
  assert.doesNotMatch(rendered.html, /<script|https?:\/\//);
  const incomplete = structuredClone(report);
  incomplete.arms[0].cases[0].validation.fullVideoDecode = false;
  assert.throws(() => renderFullVideoDecodeReport(incomplete, samples));
  const altered = structuredClone(report);
  altered.arms[0].memory.incrementalPrivateMiB--;
  assert.throws(() => renderFullVideoDecodeReport(altered, samples));
});
