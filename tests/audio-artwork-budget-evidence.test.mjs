import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import test from "node:test";
import { gunzipSync } from "node:zlib";
const root = new URL("../", import.meta.url), sha = b => createHash("sha256").update(b).digest("hex");
test("actual4MiB cover byte boundary preserves complete pixels/tags/audio with bounded inspection and unchanged full-tree accounting", async () => {
  const receipt = JSON.parse(await readFile(new URL("evidence/2026-10-25T03-32-37.015Z-audio-metadata-fidelity-result.json", root)));
  assert.equal(receipt.status, "passed-selected-small-private-cases-not-promotion"); assert.equal(receipt.publicAcceptance, false);
  assert.equal(receipt.fullMetadataAcceptance, false); assert.equal(receipt.cases.length, 1);
  assert.equal(receipt.artifactManifestSha256, "94da3c35e695c4a2b42a4a8cdd863910bbe09b2e9b46d8b66f674d075b3a658c");
  assert.equal(receipt.memory.incrementalPrivateMiB, 159.18359375); assert.equal(receipt.memory.validSamples, 438);
  assert.equal(receipt.memory.unavailableSamples, 0); assert.equal(receipt.losslessJournal.complete, true);
  const archive = await readFile(new URL(receipt.archive.path, root)); assert.equal(sha(archive), receipt.archive.sha256);
  const raw = gunzipSync(archive, { maxOutputLength: 1048576 }); assert.equal(sha(raw), receipt.archive.restoredSha256);
  assert.equal(raw.length, receipt.archive.restoredBytes); const report = JSON.parse(raw), row = receipt.cases[0];
  for (const field of ["artworkAcceptance", "scalingAcceptance", "headedCoverage", "nativeConversionUsed"]) assert.equal(report[field], false);
  assert.equal(report.artworkBudgetRecipe.realCompressedPixelBytes, 4188425); assert.equal(report.artworkBudgetRecipe.privateAncillaryPaddingBytes, 5810);
  assert.equal(report.artworkBudgetRecipe.noSparsePlaceholder, true);
  assert.equal(row.artwork.bytes, 4194304); assert.equal(row.artwork.width, 1023); assert.equal(row.artwork.height, 1023);
  assert.equal(row.artwork.sha256, "82018fd4354618bc019a1ca8ab9b4195b56ed477f976f6337b6d7e53cbcaf37f");
  assert.equal(row.artwork.decodedRgbaSha256, "4355f9c1980ad3aaf1f077d06e2b06e4d2c70f3d22143d6ed8e210203c7495ba");
  assert.deepEqual(row.artwork, report.artworkFixtures["flac-png-budget"].artwork);
  assert.equal(row.outputBytes, 5633796); assert.equal(row.tagsPreserved, 25);
  assert.deepEqual(row.repeatedValues, ["CUSTOM_REPEAT=Premier 音楽", "CUSTOM_REPEAT=Deuxième café"]);
  assert.equal(row.fidelity.samples, 96000); assert.ok(row.fidelity.psnrDb >= 60);
  const controls = JSON.parse(await readFile(new URL("evidence/2026-10-25T03-16-02.860Z-audio-metadata-fidelity-result.json", root)));
  const control = controls.cases.find(c => c.name === "flac-to-opus-repeated-values-png-cover");
  assert.equal(row.fidelity.outputSha256, control.fidelity.outputSha256); assert.equal(row.fidelity.sourceSha256, control.fidelity.sourceSha256);
  assert.equal(report.artworkFixtures["flac-png-budget"].sourcePcmUnchanged.exact, true);
  const inspection = row.streamingPictureInspection;
  assert.equal(inspection.sha256, row.artwork.sha256); assert.equal(inspection.imageBytes, 4194304);
  assert.equal(inspection.completePacketOrImageBufferAllocated, false); assert.equal(inspection.pages, 88); assert.equal(inspection.textBytes, 800);
  assert.ok(inspection.maximumReadBytes <= 65025); assert.ok(inspection.maximumBase64ChunkBytes <= 16384); assert.ok(inspection.maximumDecodedChunkBytes <= 12288);
  const metrics = report.cases[0].browserState.metrics;
  assert.equal(metrics.peakWasmMemoryBytes, 33554432); assert.equal(metrics.maxReadChunkBytes, 262144);
  assert.equal(metrics.maxWriteChunkBytes, 65307); assert.equal(metrics.peakQueuedBytes, 65307); assert.equal(metrics.peakPendingOperations, 1);
  assert.equal(metrics.pendingOperations, 0); assert.equal(metrics.queuedBytes, 0);
  assert.ok(receipt.protectedOriginalUnchanged); assert.ok(Object.values(receipt.cleanup).every(Boolean)); assert.ok(row.disposableOutputRemoved);
  assert.equal(receipt.diskProof.provesThisContextOpfsBacking, true); assert.deepEqual(receipt.network.forbidden, []); assert.deepEqual(receipt.failures, []);
  assert.ok(report.processCleanup.every(p => p.status === "owned-identity-absent"));
  const journal = await readFile(new URL(receipt.losslessJournal.file, root)); assert.equal(sha(journal), receipt.losslessJournal.archiveSha256);
  const unpacked = gunzipSync(journal, { maxOutputLength: 8 * 1048576 }); assert.equal(sha(unpacked), receipt.losslessJournal.sha256);
  const samples = unpacked.toString().trim().split("\n").map(line => JSON.parse(line).sample); assert.equal(samples.length, 438);
  for (const [index, sample] of samples.entries()) {
    assert.equal(sample.sequence, index + 1); assert.equal(sample.sampleError, null);
    assert.equal(sample.privateBytes, sample.processes.reduce((n, p) => n + p.privateBytes, 0));
  }
  const peak = Math.max(...samples.filter(s => s.phase !== "blank").map(s => s.privateBytes));
  assert.equal((peak - report.blankBaseline.privateBytes) / 1048576, receipt.memory.incrementalPrivateMiB);
  for (const screenshot of report.screenshots) assert.equal(sha(await readFile(new URL(screenshot.path, root))), screenshot.sha256);
});
