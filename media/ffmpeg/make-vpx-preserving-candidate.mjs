import assert from "node:assert/strict";
import { readFile, realpath, writeFile } from "node:fs/promises";
import path from "node:path";
import { makeVpxPreservingSource } from "./vpx-preserving-candidate.mjs";
const root = path.resolve(import.meta.dirname, "../.."), build = path.join(root, "work/ffmpeg-nondocker-build");
assert.equal(process.argv.length, 3); assert.equal(path.resolve(process.argv[2]), path.join(build, "within_remux.c"));
assert.equal(await realpath(build), build);
const source = makeVpxPreservingSource(await readFile(process.argv[2], "utf8"));
await writeFile(process.argv[2], source.generated);
console.log(JSON.stringify({ compiledSourceSha256: source.generatedSha256, edits: source.edits.length, publicAcceptance: false }));
