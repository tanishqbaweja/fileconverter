import assert from "node:assert/strict";
import { readFile, realpath, writeFile } from "node:fs/promises";
import path from "node:path";
import { makeVpxAacSource, makeVpxAacMuxSource, makeVpxTimelineSource, makeVpxTimelineMuxSource } from "./vpx-aac-candidate.mjs";
const root = path.resolve(import.meta.dirname, "../.."), build = path.join(root, "work/ffmpeg-nondocker-build");
assert.equal(await realpath(build), build);
const option = process.argv[2]; assert.equal(typeof option, "string"); const flagged = option.startsWith("--");
if (flagged) assert.ok(["--mux", "--timeline", "--mux-timeline"].includes(option));
const mux = option === "--mux" || option === "--mux-timeline", timeline = option === "--timeline" || option === "--mux-timeline";
assert.equal(process.argv.length, flagged ? 4 : 3);
const file = path.resolve(process.argv[flagged ? 3 : 2]);
assert.equal(file, path.join(build, mux ? "ffmpeg/libavformat/movenc.c" : "within_remux.c"));
const input = await readFile(file, "utf8");
const deriveMux = timeline ? makeVpxTimelineMuxSource : makeVpxAacMuxSource, deriveWrapper = timeline ? makeVpxTimelineSource : makeVpxAacSource;
const derived = mux ? deriveMux(input, await readFile(path.join(root, "media/ffmpeg/patches/mov-fragmented-aac-exact-priming.patch"), "utf8")) : deriveWrapper(input);
if (mux) await writeFile(path.join(build, "movenc.vpx-base.c"), input, { flag: "wx" });
await writeFile(file, derived.generated);
console.log(JSON.stringify({ mux, timeline, sourceSha256: derived.generatedSha256, edits: derived.edits.length, publicAcceptance: false }));
