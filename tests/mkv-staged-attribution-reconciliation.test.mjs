import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readFile } from "node:fs/promises";
import test from "node:test";
import { gunzipSync } from "node:zlib";
import { reconcileNativeBirthRole } from "../scripts/lib/native-birth-role.mjs";
const sha = b => createHash("sha256").update(b).digest("hex");
const result = JSON.parse(await readFile("evidence/2026-11-17-mkv-staged-attribution-reconciliation.json"));
const rawReceipt = await readFile(result.sourceReceipt.file);
assert.equal(sha(rawReceipt), result.sourceReceipt.sha256);
assert.equal(sha(rawReceipt), "d5edb76abe6f4a239bb44d89bcae0c121d7a4085d7964b0f797e5d62ced18258");
const r = JSON.parse(rawReceipt), a = r.arms[0];
test("offline reconciliation authenticates the full native journal, exact peak birth and both separate witnesses", async () => {
  const packed = await readFile(a.archive.file); assert.equal(sha(packed), a.archive.sha256);
  const raw = gunzipSync(packed, { maxOutputLength: 16 * 1048576 }); assert.equal(sha(raw), a.archive.decodedSha256);
  const samples = JSON.parse(raw), atPeak = samples.filter(s => s.timestamp === result.nativePeakTimestamp);
  assert.equal(samples.length, 1657); assert.equal(atPeak.length, 1);
  const peak = atPeak[0], children = peak.processes.filter(p => p.pid === result.nativeBirth.pid);
  assert.equal(children.length, 1); const child = children[0];
  for (const key of Object.keys(result.nativeBirth)) assert.equal(child[key], result.nativeBirth[key]);
  assert.equal(child.privateBytes, result.nativePeakChildPrivateBytes); assert.equal(child.privateBytes, 303366144);
  assert.deepEqual(reconcileNativeBirthRole(child, a.observer.birthTypeCapture), result.retainedObserver);
  assert.equal(result.retainedObserver.utilitySubtype, "on_device_model.mojom.OnDeviceModelService");
  assert.deepEqual(result.laterCensus, a.budgetFailureRoleDiagnostic.roles[0].result);
  assert.equal(result.laterCensus.type, null); assert.equal(result.diagnosticSnapshotPrivateBytes, 264974336);
  assert.equal(peak.processes.reduce((n, p) => n + p.privateBytes, 0), result.acceptance.peakTreePrivateBytes);
  assert.equal((peak.privateBytes - a.blank.privateBytes) / 1048576, result.acceptance.incrementalPrivateMiB);
  assert.equal(result.acceptance.incrementalPrivateMiB, 405.11328125); assert.equal(result.acceptance.passed, false);
  assert.equal(result.acceptance.processIncluded, true); assert.equal(result.acceptance.baselineChanged, false);
  assert.equal(result.diagnosticsOnly.restOfTreeDeltaNeededToPassWithSameChildMiB, -39.3125);
  assert.equal(result.diagnosticsOnly.appTriggeredServiceAllocationProven, false);
  assert.equal(sha(await readFile(result.currentHtml.file)), result.currentHtml.sha256);
});
test("transitive source provenance gap is disclosed, historical helper bytes match, and future runs pin the helper directly", async () => {
  const p = result.classifierProvenance;
  assert.equal(p.directlyPinnedInOriginalReceipt, false); assert.equal(r.sourcePins[p.file], undefined);
  const historical = execFileSync("git", ["show", `${r.executedHead}:${p.file}`], { windowsHide: true, maxBuffer: 65536 });
  assert.equal(sha(historical), p.sha256); assert.equal(sha(await readFile(p.file)), p.sha256);
  const source = await readFile("scripts/qualify-mkv-direct-reuse.mjs", "utf8");
  assert.match(source, /sourceFiles\.push\("scripts\/lib\/owned-burst-role\.mjs", "scripts\/lib\/birth-type-capture\.mjs",\s*"scripts\/lib\/birth-aware-chromium-memory\.mjs"\)/);
  assert.equal(result.newConversionPerformed, false); assert.equal(result.rawEvidenceModified, false);
  assert.equal(result.wholeGoalComplete, false);
});
